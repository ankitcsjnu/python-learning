#escape sequences 
# an escape sequence is a series of characters that represents 
# a special character when used inside a string.

"""
\n- New line
\t- Tab space
\\- Backslash
\'- Single quote
\"- Double quote
"""

print("Hello, World!")  # Normal string
print("Hello,\nWorld!")  # New line escape sequence
print("Hello,\tWorld!")  # Tab escape sequence
print("Hello, \"World\"!")  # Double quote escape sequence
print("Hello, \'World\'!")  # Single quote escape sequence
