# logical operator are used to combine  multiple condition together.
# result always in boolean 

# and :- both condition are true
# or :- atleast one condition are true
# not :- reverse the result

#example 

chemistry = 45
maths = 34

print(chemistry>33 and maths>33) # true when both condition are true

print(chemistry>33 or maths>35) # true when atleast one condition is true

print(not(chemistry>33)) # true when the condition is false